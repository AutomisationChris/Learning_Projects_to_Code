def lonlat_to_world_px(lon: float, lat: float, zoom: int) -> Tuple[float, float]:
    # WebMercator / Slippy Map pixel coords
    lat = max(min(lat, 85.05112878), -85.05112878)
    lat_rad = math.radians(lat)
    n = 2 ** zoom
    x = (lon + 180.0) / 360.0 * n * 256.0
    y = (1.0 - math.log(math.tan(lat_rad) + 1.0 / math.cos(lat_rad)) / math.pi) / 2.0 * n * 256.0
    return x, y

@st.cache_data(show_spinner=False)
def fetch_osm_tile(z: int, x: int, y: int) -> np.ndarray:
    url = f"https://tile.openstreetmap.org/{z}/{x}/{y}.png"
    req = urllib.request.Request(url, headers={"User-Agent": "streamlit-ubahn-viz/1.0"})
    with urllib.request.urlopen(req, timeout=20) as r:
        data = r.read()
    img = Image.open(io.BytesIO(data)).convert("RGB")
    return np.array(img)

@st.cache_data(show_spinner=False)
def build_basemap(bbox_lonlat: Tuple[float, float, float, float], zoom: int) -> Tuple[np.ndarray, int, int]:
    # bbox: (min_lon, max_lon, min_lat, max_lat)
    min_lon, max_lon, min_lat, max_lat = bbox_lonlat

    x0w, y1w = lonlat_to_world_px(min_lon, min_lat, zoom)  # bottom-left
    x1w, y0w = lonlat_to_world_px(max_lon, max_lat, zoom)  # top-right

    tx0, ty0 = int(x0w // 256), int(y0w // 256)
    tx1, ty1 = int(x1w // 256), int(y1w // 256)

    width = (tx1 - tx0 + 1) * 256
    height = (ty1 - ty0 + 1) * 256
    canvas = np.zeros((height, width, 3), dtype=np.uint8)

    for ty in range(ty0, ty1 + 1):
        for tx in range(tx0, tx1 + 1):
            tile = fetch_osm_tile(zoom, tx, ty)
            y = (ty - ty0) * 256
            x = (tx - tx0) * 256
            canvas[y:y+256, x:x+256, :] = tile

    return canvas, tx0, ty0


