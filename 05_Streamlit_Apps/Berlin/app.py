def sort_key_u(line_name: str) -> int:
    # "U1".."U9" -> 1..9 ; fallback large
    try:
        digits = "".join(ch for ch in str(line_name) if ch.isdigit())
        return int(digits) if digits else 999
    except Exception:
        return 999


