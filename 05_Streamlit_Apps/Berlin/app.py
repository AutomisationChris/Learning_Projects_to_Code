def active_services_for_date(date_yyyymmdd: int, cald: pd.DataFrame, calendar: Optional[pd.DataFrame]) -> set[str]:
    # Prefer full calendar if present, then apply calendar_dates exceptions.
    active = set()

    if calendar is not None and not calendar.empty:
        d = str(date_yyyymmdd)
        y, m, dd = int(d[:4]), int(d[4:6]), int(d[6:8])
        import datetime as _dt
        dow = _dt.date(y, m, dd).weekday()  # Mon=0
        dow_col = ["monday","tuesday","wednesday","thursday","friday","saturday","sunday"][dow]

        base = calendar[
            (calendar["start_date"].astype(int) <= date_yyyymmdd) &
            (calendar["end_date"].astype(int) >= date_yyyymmdd) &
            (calendar[dow_col].astype(int) == 1)
        ]
        active = set(base["service_id"].astype("string").tolist())

        # Apply exceptions
        add = cald[(cald["date"] == date_yyyymmdd) & (cald["exception_type"] == 1)]["service_id"]
        rem = cald[(cald["date"] == date_yyyymmdd) & (cald["exception_type"] == 2)]["service_id"]
        active |= set(add.astype("string").tolist())
        active -= set(rem.astype("string").tolist())

        return active

    # Fallback: only exception_type==1
    add = cald[(cald["date"] == date_yyyymmdd) & (cald["exception_type"] == 1)]["service_id"]
    return set(add.astype("string").tolist())


def iter_stop_times_filtered(stop_times_path: Path, trip_ids: set[str], chunksize: int = 600_000) -> pd.DataFrame:
    compression = "zip" if stop_times_path.suffix.lower() == ".zip" else None

    usecols = ["trip_id", "departure_time", "stop_id", "stop_sequence"]
    dtypes = {"trip_id": "string", "stop_id": "string", "stop_sequence": "int32", "departure_time": "string"}

    keep = []
    for chunk in pd.read_csv(
        stop_times_path,
        usecols=usecols,
        dtype=dtypes,
        chunksize=chunksize,
        compression=compression,
        low_memory=False,
    ):
        m = chunk["trip_id"].isin(trip_ids)
        if m.any():
            keep.append(chunk.loc[m])

    if not keep:
        return pd.DataFrame(columns=usecols)
    return pd.concat(keep, ignore_index=True)


@st.cache_data(show_spinner=False)
def build_segments_for_date(date_yyyymmdd: int) -> Dict[str, object]:
    stops, routes, trips, cald, calendar = load_small_tables()

    active_services = active_services_for_date(date_yyyymmdd, cald, calendar)
    if not active_services:
        raise RuntimeError(f"Keine active service_id für {date_yyyymmdd} gefunden.")

    # U-Bahn filter: route_short_name startswith "U" OR route_type==400
    routes_u = routes[(routes["route_short_name"].str.startswith("U")) | (routes["route_type"] == 400)].copy()
    if routes_u.empty:
        raise RuntimeError("Keine U-Bahn routes gefunden (Filter route_short_name startswith 'U' / route_type==400).")

    # Join trips->routes_u, then filter services
    trips_u = trips.merge(
        routes_u[["route_id", "route_short_name", "route_color"]],
        on="route_id",
        how="inner",
    )
    trips_u = trips_u[trips_u["service_id"].isin(active_services)].copy()
    if trips_u.empty:
        raise RuntimeError("Keine Trips für das Datum nach Service-Filter gefunden.")

    trip_ids = set(trips_u["trip_id"].astype(str).tolist())

    # Stop times (big file) – chunk read
    stop_times_path = pick_stop_times_path()
    st_active = iter_stop_times_filtered(stop_times_path, trip_ids)
    if st_active.empty:
        raise RuntimeError("Keine stop_times für die aktiven Trips gefunden (Filter evtl. falsch / Dateien mismatch).")

    # Merge coords
    st_active = st_active.merge(stops, on="stop_id", how="left").dropna(subset=["stop_lat", "stop_lon"])
    st_active["t0"] = gtfs_time_to_sec(st_active["departure_time"])
    st_active.sort_values(["trip_id", "stop_sequence"], inplace=True)

    # Build segments between consecutive stops
    g = st_active.groupby("trip_id", sort=False)
    st_active["lat1"] = g["stop_lat"].shift(-1)
    st_active["lon1"] = g["stop_lon"].shift(-1)
    st_active["t1"] = g["t0"].shift(-1)

    seg = st_active.dropna(subset=["lat1", "lon1", "t1"]).copy()
    seg.rename(columns={"stop_lat": "lat0", "stop_lon": "lon0"}, inplace=True)
    seg = seg[seg["t1"] > seg["t0"]]

    seg = seg.merge(trips_u[["trip_id", "route_short_name", "route_color"]], on="trip_id", how="left")
    seg = seg.dropna(subset=["route_short_name", "route_color"])

    # Palette mapping
    line_names = sorted(seg["route_short_name"].unique().tolist(), key=lambda x: int(x[1:]) if x[1:].isdigit() else 999)
    color_map = {ln: "#" + routes_u.loc[routes_u["route_short_name"] == ln, "route_color"].iloc[0] for ln in line_names}
    idx_map = {ln: i for i, ln in enumerate(line_names)}
    palette = [color_map[ln] for ln in line_names]
    seg["route_idx"] = seg["route_short_name"].map(idx_map).astype(np.int16)

    used_stop_ids = st_active["stop_id"].unique()
    used_stops = stops[stops["stop_id"].isin(used_stop_ids)].copy()

    # bounds from stops (padding)
    min_lon, max_lon = float(used_stops["stop_lon"].min()), float(used_stops["stop_lon"].max())
    min_lat, max_lat = float(used_stops["stop_lat"].min()), float(used_stops["stop_lat"].max())
    pad_lon = (max_lon - min_lon) * 0.15
    pad_lat = (max_lat - min_lat) * 0.15
    bbox = (min_lon - pad_lon, max_lon + pad_lon, min_lat - pad_lat, max_lat + pad_lat)

    data = {
        "t0": seg["t0"].to_numpy(np.int32),
        "t1": seg["t1"].to_numpy(np.int32),
        "lat0": seg["lat0"].to_numpy(np.float64),
        "lon0": seg["lon0"].to_numpy(np.float64),
        "lat1": seg["lat1"].to_numpy(np.float64),
        "lon1": seg["lon1"].to_numpy(np.float64),
        "route_idx": seg["route_idx"].to_numpy(np.int16),
        "palette": palette,
        "line_names": line_names,
        "stops_lat": used_stops["stop_lat"].to_numpy(np.float64),
        "stops_lon": used_stops["stop_lon"].to_numpy(np.float64),
        "bbox": bbox,
        "t_min": int(seg["t0"].min()),
        "t_max": int(seg["t1"].max()),
        "n_stops": int(len(used_stops)),
        "n_segments": int(len(seg)),
        "n_trips": int(len(trip_ids)),
    }
    return data


def canvas_to_rgb(fig) -> np.ndarray:
    # Matplotlib >=3.9 compatible
    fig.canvas.draw()
    w, h = fig.canvas.get_width_height()
    rgba = np.asarray(fig.canvas.buffer_rgba(), dtype=np.uint8).reshape(h, w, 4)
    return rgba[:, :, :3]


@st.cache_data(show_spinner=False)
def render_gif_bytes(
    date_yyyymmdd: int,
    fps: int,
    duration_sec: int,
    basemap_enabled: bool,
    basemap_zoom: int,
    size_px: int,
) -> bytes:
    data = build_segments_for_date(date_yyyymmdd)

    frames = max(1, int(duration_sec * fps))
    sim_start, sim_end = data["t_min"], data["t_max"]

    # Basemap (optional). If it fails: fallback to None.
    basemap = None
    tx0 = ty0 = 0
    if basemap_enabled:
        try:
            basemap, tx0, ty0 = build_basemap(data["bbox"], basemap_zoom)
        except Exception:
            basemap = None  # fallback

    def to_local_px(lon_arr: np.ndarray, lat_arr: np.ndarray) -> Tuple[np.ndarray, np.ndarray]:
        xs = np.empty(len(lon_arr), dtype=np.float64)
        ys = np.empty(len(lat_arr), dtype=np.float64)
        for i, (lo, la) in enumerate(zip(lon_arr, lat_arr)):
            xw, yw = lonlat_to_world_px(float(lo), float(la), basemap_zoom)
            xs[i] = xw - tx0 * 256.0
            ys[i] = yw - ty0 * 256.0
        return xs, ys

    # Precompute stop pixels if basemap exists, else use lon/lat directly
    if basemap is not None:
        stops_x, stops_y = to_local_px(data["stops_lon"], data["stops_lat"])
        bg_h, bg_w = basemap.shape[0], basemap.shape[1]
    else:
        stops_x, stops_y = data["stops_lon"], data["stops_lat"]
        # set bounds from bbox
        min_lon, max_lon, min_lat, max_lat = data["bbox"][0], data["bbox"][1], data["bbox"][2], data["bbox"][3]
        bg_w = bg_h = size_px

    pil_frames: List[Image.Image] = []

    for k in range(frames):
        sim_t = int(sim_start + (k / max(frames - 1, 1)) * (sim_end - sim_start))

        mask = (data["t0"] <= sim_t) & (data["t1"] >= sim_t)
        if np.any(mask):
            dt = (data["t1"][mask] - data["t0"][mask]).astype(np.float64)
            alpha = (sim_t - data["t0"][mask]).astype(np.float64) / dt
            lat = data["lat0"][mask] + alpha * (data["lat1"][mask] - data["lat0"][mask])
            lon = data["lon0"][mask] + alpha * (data["lon1"][mask] - data["lon0"][mask])
            colors = [data["palette"][i] for i in data["route_idx"][mask]]
        else:
            lat = np.array([], dtype=np.float64)
            lon = np.array([], dtype=np.float64)
            colors = []

        if basemap is not None:
            train_x, train_y = to_local_px(lon, lat)

            # figure size: match chosen pixel size roughly
            fig = plt.figure(figsize=(size_px / 100, size_px / 100), dpi=100)
            ax = fig.add_subplot(111)
            ax.imshow(basemap, origin="upper")
            ax.scatter(stops_x, stops_y, s=2, alpha=0.18)
            ax.scatter(train_x, train_y, s=10, c=colors, alpha=0.9)
            ax.set_xlim(0, bg_w)
            ax.set_ylim(bg_h, 0)
            ax.axis("off")
            ax.set_title(f"{date_yyyymmdd} — {sec_to_hms(sim_t)}", fontsize=14)
        else:
            # fallback plot in lon/lat (still readable if bounds are stable)
            min_lon, max_lon, min_lat, max_lat = data["bbox"][0], data["bbox"][1], data["bbox"][2], data["bbox"][3]

            fig = plt.figure(figsize=(size_px / 100, size_px / 100), dpi=100)
            ax = fig.add_subplot(111)
            ax.set_facecolor("white")
            ax.scatter(stops_x, stops_y, s=2, alpha=0.18)
            ax.scatter(lon, lat, s=10, c=colors, alpha=0.9)
            ax.set_xlim(min_lon, max_lon)
            ax.set_ylim(min_lat, max_lat)
            ax.set_aspect("equal", adjustable="box")
            ax.grid(False)
            ax.axis("off")
            ax.set_title(f"{date_yyyymmdd} — {sec_to_hms(sim_t)}", fontsize=14)

        rgb = canvas_to_rgb(fig)
        pil_frames.append(Image.fromarray(rgb))
        plt.close(fig)

    buf = io.BytesIO()
    pil_frames[0].save(
        buf,
        format="GIF",
        save_all=True,
        append_images=pil_frames[1:],
        duration=int(1000 / max(1, fps)),
        loop=0,
        optimize=False,
    )
    return buf.getvalue()


